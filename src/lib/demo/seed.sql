-- Demo database: a small coffee shop (also used for the README screenshots).
create extension pg_stat_statements;
create type order_status as enum ('pending', 'paid', 'shipped', 'delivered', 'cancelled');
create type category as enum ('coffee', 'tea', 'equipment', 'accessories');
create table customers (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  country text not null,
  created_at timestamptz not null default now()
);
comment on table customers is 'People who placed at least one order';
create table products (
  id bigint generated by default as identity primary key,
  name text not null,
  category category not null,
  price numeric(10,2) not null check (price >= 0),
  tags text[] not null default '{}',
  attributes jsonb,
  in_stock boolean not null default true
);
create table orders (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references customers(id),
  status order_status not null default 'pending',
  total numeric(10,2),
  placed_at timestamptz not null default now()
);
create table order_items (
  order_id bigint references orders(id) on delete cascade,
  product_id bigint references products(id),
  quantity int not null check (quantity > 0),
  primary key (order_id, product_id)
);
create index orders_customer_idx on orders (customer_id);
create index orders_placed_idx on orders (placed_at desc);

