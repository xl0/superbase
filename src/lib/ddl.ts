/** Pure DDL generation for the schema forms. Output is previewed, then run as one transaction. */
import type { Table } from './types.js';
import type { ReferentialAction, SchemaColumn, SchemaType } from './schema.js';

export type ColumnDefault =
	| { kind: 'keep' | 'none' | 'identity' }
	| { kind: 'literal'; value: string }
	| { kind: 'expression'; sql: string };

/** typeOid null keeps an existing column's type. typeModifiers is raw text such as "10, 2". */
export interface ColumnSpec {
	name: string;
	typeOid: string | null;
	typeModifiers: string;
	nullable: boolean;
	default: ColumnDefault;
	comment: string;
	primaryKey: boolean;
}

export type ConstraintSpec =
	| { kind: 'unique'; name: string; columns: string[] }
	| { kind: 'check'; name: string; expression: string }
	| { kind: 'foreignKey'; name: string; columns: string[]; reference: { schema: string; table: string; columns: string[] };
		onUpdate: ReferentialAction; onDelete: ReferentialAction };

export const ident = (name: string) => `"${name.replaceAll('"', '""')}"`;
export const qualify = (schema: string, name: string) => `${ident(schema)}.${ident(name)}`;
/** Same escaping as pg.escapeLiteral: correct regardless of standard_conforming_strings. */
export function literal(value: string): string {
	const quoted = `'${value.replaceAll("'", "''").replaceAll('\\', '\\\\')}'`;
	return value.includes('\\') ? `E${quoted}` : quoted;
}

/** Real arrays resolve to their element; domains (even over arrays) stay as they are. */
export function elementType(type: SchemaType | undefined, types: SchemaType[]): SchemaType | undefined {
	return type?.kind === 'array' ? types.find((item) => item.oid === type.elementOid) : type;
}

export const MODIFIABLE_TYPES = ['numeric', 'varchar', 'bpchar', 'bit', 'varbit', 'timestamp', 'timestamptz', 'time', 'timetz'];

export function typeSql(typeOid: string, modifiers: string, types: SchemaType[]): string {
	const type = types.find((item) => item.oid === typeOid);
	const base = elementType(type, types);
	if (!type || !base) throw new Error('Choose a column type');
	const name = base.schema === 'pg_catalog' ? base.name : qualify(base.schema, base.name);
	return `${name}${modifiers.trim() ? `(${modifiers.trim()})` : ''}${type.kind === 'array' ? '[]' : ''}`;
}

/** Common default expressions offered for a column type. */
export function defaultPresets(type: SchemaType | undefined): { label: string; sql: string }[] {
	if (type?.schema !== 'pg_catalog' || type.kind !== 'base') return [];
	switch (type.name) {
		case 'timestamp': case 'timestamptz': return [{ label: 'Current timestamp', sql: 'now()' }];
		case 'date': return [{ label: 'Current date', sql: 'current_date' }];
		case 'time': return [{ label: 'Current time', sql: 'localtime' }];
		case 'timetz': return [{ label: 'Current time', sql: 'current_time' }];
		case 'uuid': return [{ label: 'Random UUID', sql: 'gen_random_uuid()' }];
		case 'text': case 'varchar': return [{ label: 'Random UUID as text', sql: 'gen_random_uuid()::text' }];
		default: return [];
	}
}

export const identityAllowed = (type: SchemaType | undefined) =>
	type?.schema === 'pg_catalog' && ['int2', 'int4', 'int8'].includes(type.name);

const defaultSql = (value: ColumnDefault) =>
	value.kind === 'literal' ? literal(value.value) : value.kind === 'expression' ? value.sql : '';

function columnSql(column: ColumnSpec, types: SchemaType[]): string {
	let sql = `${ident(column.name)} ${typeSql(column.typeOid!, column.typeModifiers, types)}`;
	if (column.default.kind === 'identity') sql += ' generated by default as identity';
	else if (defaultSql(column.default)) sql += ` default ${defaultSql(column.default)}`;
	if (!column.nullable && !column.primaryKey) sql += ' not null';
	return sql;
}

const commentSql = (table: string, column: string, comment: string) =>
	`comment on column ${table}.${ident(column)} is ${comment ? literal(comment) : 'null'};`;

export function createTable(schema: string, name: string, columns: ColumnSpec[], types: SchemaType[]): string {
	const table = qualify(schema, name);
	const lines = columns.map((column) => columnSql(column, types));
	const pk = columns.filter((column) => column.primaryKey).map((column) => ident(column.name));
	if (pk.length) lines.push(`primary key (${pk.join(', ')})`);
	return [`create table ${table} (\n  ${lines.join(',\n  ')}\n);`,
		...columns.filter((column) => column.comment).map((column) => commentSql(table, column.name, column.comment))].join('\n');
}

export function addColumn(table: string, column: ColumnSpec, types: SchemaType[]): string {
	return [`alter table ${table} add column ${columnSql(column, types)};`,
		column.primaryKey ? `alter table ${table} add primary key (${ident(column.name)});` : '',
		column.comment ? commentSql(table, column.name, column.comment) : ''].filter(Boolean).join('\n');
}

/** Statements for the changed parts only; the rename runs last so earlier statements use the old name. */
export function alterColumn(table: string, old: SchemaColumn & { primaryKey: boolean }, next: ColumnSpec, types: SchemaType[]): string {
	const alter = `alter table ${table} alter column ${ident(old.name)}`;
	const statements: string[] = [];
	if (next.default.kind !== 'keep' && old.defaultValue !== null && !old.identity) statements.push(`${alter} drop default;`);
	if (next.typeOid !== null) {
		const type = typeSql(next.typeOid, next.typeModifiers, types);
		statements.push(`${alter} type ${type} using ${ident(old.name)}::${type};`);
	}
	if (defaultSql(next.default)) statements.push(`${alter} set default ${defaultSql(next.default)};`);
	const addingKey = next.primaryKey && !old.primaryKey;
	const nullable = next.nullable && !next.primaryKey;
	// Adding a primary key sets NOT NULL itself.
	if (nullable !== old.nullable && !addingKey) statements.push(`${alter} ${nullable ? 'drop' : 'set'} not null;`);
	if (addingKey) statements.push(`alter table ${table} add primary key (${ident(old.name)});`);
	if (next.comment !== (old.comment ?? '')) statements.push(commentSql(table, old.name, next.comment));
	if (next.name !== old.name) statements.push(`alter table ${table} rename column ${ident(old.name)} to ${ident(next.name)};`);
	return statements.join('\n');
}

/** LIKE copies columns, defaults, constraints, indexes and comments. Serial columns keep sharing the source sequence. */
export function duplicateTable(source: Table, name: string, includeRows: boolean): string {
	const from = qualify(source.schema, source.name);
	const to = qualify(source.schema, name);
	const statements = [`create table ${to} (like ${from} including all);`];
	if (includeRows) {
		const columns = source.columns.filter((column) => !column.generated).map((column) => ident(column.name)).join(', ');
		statements.push(`insert into ${to} (${columns}) overriding system value select ${columns} from ${from};`);
		// New identity sequences must continue after the copied values.
		for (const column of source.columns.filter((column) => column.identity)) {
			statements.push(`select setval(pg_get_serial_sequence(${literal(to)}, ${literal(column.name)}), coalesce(max(${ident(column.name)}), 0) + 1, false) from ${to};`);
		}
	}
	return statements.join('\n');
}

export function constraintSql(spec: ConstraintSpec): string {
	const columns = (names: string[]) => names.map(ident).join(', ');
	switch (spec.kind) {
		case 'unique': return `unique (${columns(spec.columns)})`;
		case 'check': return `check (${spec.expression})`;
		case 'foreignKey': return `foreign key (${columns(spec.columns)}) references ${qualify(spec.reference.schema, spec.reference.table)} `
			+ `(${columns(spec.reference.columns)}) on update ${spec.onUpdate} on delete ${spec.onDelete}`;
	}
}
