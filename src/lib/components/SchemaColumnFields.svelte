<script lang="ts">
	import type { SchemaColumn, SchemaType } from '#lib/schema.js';
	import { defaultPresets, identityAllowed, type ColumnSpec } from '#lib/ddl.js';
	import { Input } from '#lib/components/ui/input/index.js';
	import { Textarea } from '#lib/components/ui/textarea/index.js';
	import { Checkbox } from '#lib/components/ui/checkbox/index.js';
	import { Label } from '#lib/components/ui/label/index.js';
	import * as Select from '#lib/components/ui/select/index.js';
	import SchemaTypePicker from './SchemaTypePicker.svelte';

	let { value = $bindable(), types, existing, canSetPrimaryKey, disabled = false }: {
		value: ColumnSpec; types: SchemaType[]; existing?: SchemaColumn & { primaryKey: boolean };
		canSetPrimaryKey: boolean; disabled?: boolean;
	} = $props();
	const id = $props.id();
	const type = $derived(types.find((type) => type.oid === (value.typeOid ?? existing?.typeOid)));
	const choices = $derived(type?.name === 'bool' ? ['true', 'false'] : type?.kind === 'enum' ? type.enumValues : null);
	const fixedDefault = $derived(!!(existing?.identity || existing?.generated));
	const options = $derived([
		...(existing ? [{ value: 'keep', label: `Keep: ${existing.defaultValue ?? 'no default'}` }] : []),
		{ value: 'none', label: 'No default' },
		{ value: 'literal', label: 'Value' },
		{ value: 'expression', label: 'SQL expression' },
		...defaultPresets(type).map((preset) => ({ value: `preset:${preset.sql}`, label: preset.label })),
		...(!existing && identityAllowed(type) ? [{ value: 'identity', label: 'Identity (generated by default)' }] : [])
	]);
	const selected = $derived.by(() => {
		const current = value.default;
		const preset = current.kind === 'expression' ? `preset:${current.sql}` : '';
		return options.some((option) => option.value === preset) ? preset : current.kind;
	});

	function setDefault(choice: string) {
		if (choice.startsWith('preset:')) value.default = { kind: 'expression', sql: choice.slice(7) };
		else if (choice === 'literal') value.default = { kind: 'literal', value: '' };
		else if (choice === 'expression') value.default = { kind: 'expression', sql: '' };
		else value.default = { kind: choice as 'keep' | 'none' | 'identity' };
		if (choice === 'identity') value.nullable = false;
	}
</script>

<div class="grid gap-4 @min-[540px]:grid-cols-2">
	<div class="space-y-2">
		<Label for={`${id}-name`}>Name</Label>
		<Input id={`${id}-name`} bind:value={value.name} {disabled} autocomplete="off" spellcheck={false} placeholder="column_name" class="font-mono text-xs" />
	</div>
	<SchemaTypePicker bind:value {types} {existing} disabled={disabled || !!existing?.generated} />
	<div class="space-y-2 @min-[540px]:col-span-2">
		<Label for={`${id}-default`}>Default</Label>
		{#if fixedDefault}
			<Input id={`${id}-default`} readonly value={existing?.identity ? `Identity (${existing.identity})` : `Generated: ${existing?.defaultValue}`} class="font-mono text-xs" />
		{:else}
			<Select.Root type="single" value={selected} allowDeselect={false} {disabled} onValueChange={setDefault}>
				<Select.Trigger id={`${id}-default`} class="w-full min-w-0 text-xs"><span class="truncate">{options.find((option) => option.value === selected)?.label}</span></Select.Trigger>
				<Select.Content>{#each options as option}<Select.Item value={option.value} label={option.label} class="text-xs" />{/each}</Select.Content>
			</Select.Root>
			{#if value.default.kind === 'literal'}
				{#if choices}
					<Select.Root type="single" bind:value={value.default.value} allowDeselect={false} {disabled}>
						<Select.Trigger aria-label="Default value" class="w-full text-xs">{value.default.value || 'Choose a value'}</Select.Trigger>
						<Select.Content>{#each choices as choice}<Select.Item value={choice} label={choice || '(empty)'} />{/each}</Select.Content>
					</Select.Root>
				{:else}
					<Input bind:value={value.default.value} aria-label="Default value" {disabled} spellcheck={false} class="font-mono text-xs" placeholder="Literal value (quoted for you)" />
				{/if}
			{:else if value.default.kind === 'expression'}
				<Input bind:value={value.default.sql} aria-label="Default expression" {disabled} spellcheck={false} class="font-mono text-xs" placeholder="now()" />
			{/if}
		{/if}
	</div>
	<div class="space-y-2 @min-[540px]:col-span-2">
		<Label for={`${id}-comment`}>Description</Label>
		<Textarea id={`${id}-comment`} bind:value={value.comment} {disabled} class="min-h-16 text-xs" />
	</div>
	<div class="flex flex-wrap items-center gap-x-5 gap-y-3 @min-[540px]:col-span-2">
		<div class="flex items-center gap-2">
			<!-- A primary key is NOT NULL by itself; `nullable` keeps the choice for when the key is unticked. -->
			<Checkbox id={`${id}-nullable`} checked={value.nullable && !value.primaryKey} onCheckedChange={(checked) => value.nullable = checked} disabled={disabled || value.primaryKey || value.default.kind === 'identity' || !!existing?.identity} />
			<Label for={`${id}-nullable`} class="text-xs">Allow NULL</Label>
		</div>
		<div class="flex items-center gap-2">
			<Checkbox id={`${id}-pk`} checked={value.primaryKey} disabled={disabled || !canSetPrimaryKey || !!existing?.primaryKey}
				onCheckedChange={(checked) => value.primaryKey = checked} />
			<Label for={`${id}-pk`} class="text-xs">Primary key</Label>
		</div>
	</div>
</div>
