import { afterAll, beforeAll, describe, expect, test } from 'bun:test';
import pg from 'pg';

import { deleteRows, listRows, listTables, saveTable } from '../src/lib/queries/db.js';
import type { RowFilter, RowIdentity, RowsArgs, Values } from '../src/lib/types.js';

// Never fall back to DATABASE_URL: integration tests require an explicit disposable test database.
const url = process.env.TEST_DATABASE_URL;
const schema = `sb_test_${process.pid}_${crypto.randomUUID().replaceAll('-', '')}`;
let pool: pg.Pool;
let created = false;
const target = (table: string) => ({ connection: 'test', schema, table });
const rows = (table: string, overrides: Partial<RowsArgs> = {}) =>
	listRows(pool, { ...target(table), page: 0, pageSize: 100, sort: [], search: '', ...overrides });
const insert = (table: string, inserts: Values[]) => saveTable(pool, { ...target(table), updates: [], inserts });

(url ? describe : describe.skip)('PostgreSQL text rows and optimistic transactions', () => {
	beforeAll(async () => {
		pool = new pg.Pool({ connectionString: url, max: 4 });
		await pool.query(`create schema "${schema}"`);
		created = true;
		await pool.query(`
			create type "${schema}".mood as enum ('quiet', 'loud');
			create table "${schema}".exact (
				id bigint primary key, amount numeric(40,10), doc json, binary_doc jsonb,
				items text[], numbers bigint[], empty text, nullable text,
				stamp timestamptz, enabled boolean, mood "${schema}".mood
			);
			create table "${schema}".defaults (
				id bigint generated always as identity primary key,
				n integer default 7,
				doubled integer generated always as (n * 2) stored,
				label text default 'default label'
			);
			create table "${schema}".by_default (
				id bigint generated by default as identity primary key,
				parent bigint references "${schema}".defaults(id)
			);
			create table "${schema}".inherited (id integer primary key, payload text);
			create table "${schema}".child () inherits ("${schema}".inherited);
			insert into "${schema}".inherited values (1, 'parent');
			insert into "${schema}".child values (1, 'child');
			create table "${schema}".conflicts (id integer primary key, payload text);
			insert into "${schema}".conflicts values (1, 'first'), (2, 'second'), (3, 'third');
			create table "${schema}".keyless (payload text);
			insert into "${schema}".keyless values ('a'), ('a');
			create table "${schema}".structured_filters (
				id bigint primary key, amount numeric(40,10), label text, nullable text
			);
			insert into "${schema}".structured_filters values
				(2, 2, 'Alpha_One', null),
				(10, 10, 'AlphaXOne', ''),
				(11, 11, 'alpha%Two', 'x'),
				(9007199254740992, 123456789012345678901234567890.1234567890, '', null),
				(9007199254740993, 123456789012345678901234567890.1234567891, null, 'x');
		`);
		await listTables(pool);
	});

	afterAll(async () => {
		if (!pool) return;
		try {
			if (created) await pool.query(`drop schema "${schema}" cascade`);
		} finally {
			await pool.end();
		}
	});

	test('keeps numeric, JSON, arrays, timestamps, booleans and null as PostgreSQL text', async () => {
		const original: Values = {
			id: '9223372036854775807',
			amount: '123456789012345678901234567890.1234567890',
			doc: '{ "big": 123456789012345678901234567890, "duplicate": 1, "duplicate": 2 }',
			binary_doc: '{"number":123456789012345678901234567890}',
			items: '[0:4]={"a,b","NULL",NULL,"","a\\\\b"}',
			numbers: '{9223372036854775807,-9223372036854775808}',
			empty: '', nullable: null, stamp: '2024-01-02 03:04:05.123456+00', enabled: 't', mood: 'quiet'
		};
		expect(await insert('exact', [original])).toEqual({ updated: 0, inserted: 1 });
		const [row] = (await rows('exact')).rows;
		for (const [name, value] of Object.entries(original)) {
			if (name !== 'binary_doc') expect(row.values[name]).toBe(value);
		}
		expect(row.values.binary_doc).toBe('{"number": 123456789012345678901234567890}');
		expect(row.identity!.pk.id).toBe(original.id);
		expect(Object.values(row.values).every((value) => value === null || typeof value === 'string')).toBe(true);
		const changes = { amount: '999999999999999999999999999999.0000000001', doc: '{ "n": 9007199254740993 }', items: '{"new,value",NULL}', empty: null };
		await saveTable(pool, { ...target('exact'), updates: [{ identity: row.identity!, changes }], inserts: [] });
		const [updated] = (await rows('exact')).rows;
		for (const [name, value] of Object.entries(changes)) expect(updated.values[name]).toBe(value);
		expect(updated.key).not.toBe(row.key);
		expect(updated.identity!.version).not.toBe(row.identity!.version);
		// No process-global pg parser modifications.
		const native = await pool.query('select 42::int4 as n, true as b, \'{"a":1}\'::json as doc');
		expect(native.rows[0]).toEqual({ n: 42, b: true, doc: { a: 1 } });
	});

	test('structured comparisons use native numeric ordering, exact precision and same-column AND ranges', async () => {
		const ids = async (filters: RowFilter[]) =>
			(await rows('structured_filters', { filters })).rows.map((row) => row.values.id);
		expect(await ids([
			{ column: 'id', operator: 'gt', value: '2' },
			{ column: 'id', operator: 'lt', value: '11' }
		])).toEqual(['10']);
		expect(await ids([
			{ column: 'id', operator: 'gte', value: '9007199254740992' },
			{ column: 'id', operator: 'lte', value: '9007199254740993' },
			{ column: 'id', operator: 'neq', value: '9007199254740992' }
		])).toEqual(['9007199254740993']);
		expect(await ids([{ column: 'id', operator: 'eq', value: ' 10 ' }])).toEqual(['10']);
		expect(await ids([{
			column: 'amount', operator: 'gt', value: '123456789012345678901234567890.1234567890'
		}])).toEqual(['9007199254740993']);
		expect(await ids([{ column: 'amount', operator: 'eq', value: '2.000' }])).toEqual(['2']);
		expect(await ids([])).toHaveLength(5);
		// Patterns match a non-text column's text.
		expect(await ids([{ column: 'id', operator: 'like', value: '1_' }])).toEqual(['10', '11']);
		for (const filter of [
			{ column: 'id', operator: 'eq', value: "2 OR true --" },
			{ column: 'amount', operator: 'gt', value: '' }
		] satisfies RowFilter[]) {
			await expect(ids([filter])).rejects.toThrow(/invalid input syntax/);
		}
	});

	test('only known columns and operators reach SQL; directions are whitelisted', async () => {
		const valid = { column: 'id', operator: 'eq' as const, value: '2' };
		await expect(rows('structured_filters', { filters: [{ ...valid, column: 'id" = 2 OR true --' }] })).rejects.toThrow('Unknown column');
		await expect(rows('structured_filters', { filters: [{ ...valid, operator: '__proto__' as 'eq' }] })).rejects.toThrow('Unknown filter operator');
		const injected = await rows('structured_filters', { sort: [{ column: 'id', direction: 'desc; select 1' as 'desc' }] });
		expect(injected.rows.map((row) => row.values.id)[0]).toBe('2');
	});

	test('omissions use defaults; rejects generated, always identity, unknown and non-text inputs', async () => {
		await insert('defaults', [{}]);
		const [row] = (await rows('defaults')).rows;
		expect(row.values).toEqual({ id: '1', n: '7', doubled: '14', label: 'default label' });
		await insert('defaults', [{ n: '9', label: null }]);
		expect((await rows('defaults')).rows[1].values).toEqual({ id: '2', n: '9', doubled: '18', label: null });
		await insert('by_default', [{ id: '99', parent: row.values.id }]);
		for (const changes of [{ id: '100' }, { doubled: '3' }, { missing: 'x' }]) {
			await expect(insert('defaults', [changes])).rejects.toThrow();
			await expect(saveTable(pool, { ...target('defaults'), updates: [{ identity: row.identity!, changes }], inserts: [] })).rejects.toThrow();
		}
		await expect(insert('defaults', [{ n: 'not a number' }])).rejects.toThrow();
	});

	test('tableoid scopes duplicate inherited PKs to exactly one physical relation', async () => {
		const all = (await rows('inherited')).rows;
		expect(all).toHaveLength(2);
		expect(new Set(all.map((row) => row.key)).size).toBe(2);
		const child = all.find((row) => row.values.payload === 'child')!;
		await saveTable(pool, { ...target('inherited'), updates: [{ identity: child.identity!, changes: { payload: 'updated child' } }], inserts: [] });
		expect((await rows('inherited')).rows.map((row) => row.values.payload).sort()).toEqual(['parent', 'updated child']);
		const updated = (await rows('inherited')).rows.find((row) => row.values.payload === 'updated child')!;
		await deleteRows(pool, { ...target('inherited'), identities: [updated.identity!] });
		expect((await rows('inherited')).rows.map((row) => row.values.payload)).toEqual(['parent']);
		// Inherited children need not enforce the parent's PK. Never accept a multi-row match.
		await pool.query(`insert into "${schema}".child values (9, 'duplicate'), (9, 'duplicate')`);
		const duplicates = (await rows('inherited', { search: 'duplicate' })).rows;
		expect(new Set(duplicates.map((row) => row.key)).size).toBe(2);
		expect(duplicates[0].identity).toEqual(duplicates[1].identity);
		const [duplicate] = duplicates;
		await expect(saveTable(pool, {
			...target('inherited'), updates: [{ identity: duplicate.identity!, changes: { payload: 'must roll back' } }], inserts: []
		})).rejects.toThrow('conflict');
		await expect(deleteRows(pool, { ...target('inherited'), identities: [duplicate.identity!] })).rejects.toThrow('conflict');
		expect((await rows('inherited', { search: 'duplicate' })).rows).toHaveLength(2);
	});

	test('stale updates/deletes conflict and roll back every preceding write', async () => {
		const initial = (await rows('conflicts')).rows;
		await pool.query(`update "${schema}".conflicts set payload = 'concurrent' where id = 2`);
		await expect(saveTable(pool, {
			...target('conflicts'),
			updates: [
				{ identity: initial[0].identity!, changes: { payload: 'must roll back' } },
				{ identity: initial[1].identity!, changes: { payload: 'stale' } }
			], inserts: [{ id: '4', payload: 'must not appear' }]
		})).rejects.toThrow('conflict');
		expect((await rows('conflicts')).rows.map((row) => row.values.payload)).toEqual(['first', 'concurrent', 'third']);
		await expect(deleteRows(pool, { ...target('conflicts'), identities: [initial[0].identity!, initial[1].identity!] })).rejects.toThrow('conflict');
		expect((await rows('conflicts')).rows).toHaveLength(3);
		// Insert validation/constraint failures also undo preceding updates and inserts.
		const current = (await rows('conflicts')).rows;
		await expect(saveTable(pool, {
			...target('conflicts'), updates: [{ identity: current[0].identity!, changes: { payload: 'rollback again' } }],
			inserts: [{ id: '4', payload: 'valid' }, { id: '3', payload: 'duplicate' }]
		})).rejects.toThrow();
		expect((await rows('conflicts')).rows.map((row) => row.values.payload)).toEqual(['first', 'concurrent', 'third']);
		const forged = { ...current[0].identity!, relation: '0' };
		await expect(deleteRows(pool, { ...target('conflicts'), identities: [forged] })).rejects.toThrow('conflict');
		await pool.query(`delete from "${schema}".conflicts where id = 3`);
		await expect(saveTable(pool, { ...target('conflicts'), updates: [{ identity: current[2].identity!, changes: { payload: 'gone' } }], inserts: [] })).rejects.toThrow('conflict');
	});

	test('keyless rows have display keys only and refuse every mutation', async () => {
		const page = await rows('keyless');
		expect(page.rows).toHaveLength(2);
		expect(page.rows.every((row) => row.identity === null)).toBe(true);
		expect(new Set(page.rows.map((row) => row.key)).size).toBe(2);
		expect((await rows('keyless')).rows.map((row) => row.key)).toEqual(page.rows.map((row) => row.key));
		await expect(insert('keyless', [{ payload: 'forbidden' }])).rejects.toThrow('read-only');
		await expect(saveTable(pool, { ...target('keyless'), updates: [], inserts: [] })).rejects.toThrow('read-only');
		await expect(deleteRows(pool, { ...target('keyless'), identities: [{ pk: {}, version: '1', relation: '1' }] })).rejects.toThrow('read-only');
	});

	test('plain and materialized views read as read-only tables, with and without a sort', async () => {
		await pool.query(`
			create view "${schema}".exact_view as select id, amount from "${schema}".exact;
			create materialized view "${schema}".exact_matview as select id, amount from "${schema}".exact`);
		const { tables } = await listTables(pool);
		const kinds = Object.fromEntries(tables.filter((table) => table.schema === schema).map((table) => [table.name, table.kind]));
		expect(kinds).toMatchObject({ exact: 'table', exact_view: 'view', exact_matview: 'materialized view' });
		for (const name of ['exact_view', 'exact_matview']) {
			for (const sort of [[], [{ column: 'id', direction: 'desc' as const }]]) {
				const page = await rows(name, { sort });
				expect(page.rows.length).toBeGreaterThan(0);
				expect(page.rows.every((row) => row.identity === null)).toBe(true);
				expect(new Set(page.rows.map((row) => row.key)).size).toBe(page.rows.length);
			}
		}
	});

	test('acting as a role applies its RLS policies and session settings to reads and writes', async () => {
		const role = `sb_test_role_${process.pid}`;
		const table = `"${schema}".owned`;
		await pool.query(`
			create role ${role};
			grant usage on schema "${schema}" to ${role};
			create table ${table} (id int primary key, owner text not null);
			insert into ${table} values (1, 'ann'), (2, 'bob');
			alter table ${table} enable row level security;
			create policy mine on ${table} to ${role}
			  using (owner = current_setting('app.who', true)) with check (owner = current_setting('app.who', true));
			grant select, insert, update, delete on ${table} to ${role}`);
		await listTables(pool);
		try {
			const as = { role, settings: { 'app.who': 'ann' } };
			expect((await rows('owned', { as })).rows.map((row) => row.values.id)).toEqual(['1']);
			expect((await rows('owned')).rows).toHaveLength(2);
			await saveTable(pool, { ...target('owned'), as, updates: [], inserts: [{ id: '3', owner: 'ann' }] });
			await expect(saveTable(pool, { ...target('owned'), as, updates: [], inserts: [{ id: '4', owner: 'bob' }] })).rejects.toThrow('row-level security');
		} finally {
			await pool.query(`drop table ${table}; drop owned by ${role}; drop role ${role}`);
		}
	});
});
